"""Produce public-API test calls for each supported Fortran type and rank."""
from pathlib import Path


def generate():
    text = '''! Generated by scripts/generate_fortran_array_tests.py
program typed
  use iso_c_binding
  use mpi
  use cotocoa
  implicit none
  type(ctca_context) :: ctx
  type(ctca_message) :: message
  integer :: dtype, ndim, rank, ierr
  character(len=1024) :: name, config, env
  call get_command_argument(1,name)
  call get_command_argument(2,config)
  call get_environment_variable('COTOCOA_TEST_DTYPE',env)
  read(env,*) dtype
  call get_environment_variable('COTOCOA_TEST_NDIM',env)
  read(env,*) ndim
  call ctx%open(trim(name),config=trim(config))
  call MPI_Comm_rank(ctx%comm(),rank,ierr)
  select case(dtype*10+ndim)
'''
    for dtype in range(1,4):
        for ndim in range(1,4):
            text += f'  case({dtype*10+ndim})\n    call array_{dtype}_{ndim}()\n'
    text += '''  end select
  call ctx%close()
contains
  subroutine require(condition,text)
    logical, intent(in) :: condition
    character(len=*), intent(in) :: text
    if (.not. condition) then
      print *, 'FAIL typed Fortran: ',text
      call MPI_Abort(MPI_COMM_WORLD,1,ierr)
    end if
  end subroutine
'''
    for dtype, declaration in ((1,'real(c_double)'),(2,'real(c_float)'),(3,'integer(c_int32_t)')):
        for ndim in range(1,4):
            storage = ','.join(str(s) for s in (6,5,7)[:ndim])
            dims = ','.join(':' for _ in range(ndim))
            slice_ = ','.join(('1:6:2',':',':')[:ndim])
            axes = ['i','j','k'][:ndim]
            at = ','.join(axes)
            store_at = ','.join(['i*2-1', *axes[1:]])
            expected = '-1000000+source*1000000+step*1000+(i-1)*100'
            if ndim>=2: expected += '+(j-1)*10'
            if ndim>=3: expected += '+k-1'
            expected_shape = ','.join(str(s) for s in (3,5,7)[:ndim])
            loops = ''.join(f'      do {axis}=1,{s}\n' for axis,s in reversed(list(zip(axes,(3,5,7)[:ndim]))))
            ends = '      end do\n'*ndim
            text += f'''
  subroutine array_{dtype}_{ndim}()
    {declaration} :: field({storage})
    {declaration}, allocatable :: received({dims})
    integer(c_int64_t) :: offset({ndim})
    integer :: step, source, i, j, k, count
    logical :: available
    if (trim(name)=='producer') then
      source=rank
      do step=1,8
{loops}        field({store_at}) = {expected}
{ends}        offset=0_c_int64_t
        offset(1)=int(rank*3,c_int64_t)
        call ctx%send('field',field({slice_}),step=int(step,c_int64_t),offset=offset)
        field=0
      end do
    else
      count=0
      do
        call ctx%receive('field',message,has_message=available)
        if (.not. available) exit
        call message%copy_to(received)
        source=message%source_rank()
        step=int(message%step())
        call require(message%dtype()=={dtype} .and. message%ndim()=={ndim},'type and rank')
        call require(all(shape(received)==[{expected_shape}]),'shape')
{loops}        call require(received({at}) == {expected},'noncontiguous snapshot')
{ends}        call message%complete()
        count=count+1
      end do
      call require(count==16,'all delivery count')
      print *, 'PASS typed Fortran dtype={dtype} ndim={ndim} rank=',rank
    end if
  end subroutine
'''
    return text+'end program typed\n'


if __name__ == '__main__':
    (Path(__file__).resolve().parents[1]/'tests/typed.f90').write_text(generate())
