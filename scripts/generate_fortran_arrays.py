"""Regenerate the checked-in type/rank overloads; not required for building."""
from pathlib import Path


def generate():
    parts = ["! Generated by scripts/generate_fortran_arrays.py; edit the generator.\n"]
    for suffix, declaration, dtype, constructor in (
        ("real64", "real(c_double)", 1, "c_make_view"),
        ("real32", "real(c_float)", 2, "c_make_view_f32"),
        ("int32", "integer(c_int32_t)", 3, "c_make_view_i32"),
    ):
        for rank in (1, 2, 3):
            dims = ', '.join(':' for _ in range(rank))
            first = ', '.join('1' for _ in range(rank))
            parts.append(f'''
  subroutine send_{suffix}_{rank}(self, name, array, step, time, offset, status)
    class(ctca_context), intent(inout) :: self
    character(len=*), intent(in) :: name
    {declaration}, contiguous, target, intent(in) :: array({dims})
    integer(c_int64_t), intent(in) :: step
    real(c_double), optional, intent(in) :: time
    integer(c_int64_t), optional, intent(in) :: offset({rank})
    type(ctca_status), optional, intent(out) :: status
    type(c_error) :: error
    type(c_options) :: options
    type(c_view) :: view
    type(c_ptr) :: data
    integer(c_int64_t) :: sizes(3)
    integer(c_int) :: rc
    data = c_null_ptr
    if (size(array) > 0) data = c_loc(array({first}))
    sizes = 1_c_int64_t
    sizes(:{rank}) = shape(array, kind=c_int64_t)
    view = {constructor}(data, {rank}_c_int, sizes, 1_c_int)
    options%step = step
    options%has_time = 0
    options%time = 0.0_c_double
    options%offset = 0_c_int64_t
    if (present(time)) then
      options%has_time = 1
      options%time = time
    end if
    if (present(offset)) options%offset(:{rank}) = offset
    rc = c_send(self%handle, trim(name)//c_null_char, view, options, error)
    call report(rc, error, self%handle, status)
  end subroutine

  subroutine copy_{suffix}_{rank}(self, array, status)
    class(ctca_message), intent(in) :: self
    {declaration}, allocatable, intent(out) :: array({dims})
    type(ctca_status), optional, intent(out) :: status
    type(c_error) :: error
    type(c_view) :: view
    {declaration}, pointer :: source({dims})
    integer(c_int) :: rc
    rc = c_get_view(self%handle, view, error)
    if (rc == 0) then
      if (view%ndim /= {rank} .or. view%dtype /= {dtype}) then
        call local_error(error, 'copy_to: destination type or rank differs from the message')
        rc = error%code
      else
        call c_f_pointer(view%data, source, int(view%shape(:{rank})))
        array = source
      end if
    end if
    call report(rc, error, c_null_ptr, status)
  end subroutine
''')
    # Submit uses the same typed descriptors and packing rules as send. The
    # caller supplies a ticket variable, so replacing it can release its old
    # local reference without losing or cancelling the underlying request.
    for suffix in ('real64','real32','int32'):
        for rank in (1,2,3):
            text=''.join(parts)
            start=text.index(f'  subroutine send_{suffix}_{rank}(')
            end=text.index('  end subroutine',start)+len('  end subroutine')
            submit=text[start:end]
            submit=submit.replace(f'send_{suffix}_{rank}(',f'submit_{suffix}_{rank}(')
            submit=submit.replace('(self, name, array, step,','(self, name, array, ticket, step,')
            submit=submit.replace('    integer(c_int64_t), intent(in) :: step',
                '    type(ctca_ticket), intent(inout) :: ticket\n    integer(c_int64_t), optional, intent(in) :: step')
            submit=submit.replace('    options%step = step',
                '    options%step = 0_c_int64_t\n    if (present(step)) options%step = step')
            submit=submit.replace('    rc = c_send(self%handle, trim(name)//c_null_char, view, options, error)',
                '    call ticket%release()\n    rc = c_submit(self%handle, trim(name)//c_null_char, &\n' +
                '                  view, options, ticket%handle, error)')
            parts.append('\n'+submit+'\n')
    for suffix in ('real64','real32','int32'):
        for rank in (1,2,3):
            text=''.join(parts)
            start=text.index(f'  subroutine submit_{suffix}_{rank}(')
            end=text.index('  end subroutine',start)+len('  end subroutine')
            template=text[start:end].replace('contiguous, target','target, asynchronous')
            stride_code=''
            for dim in range(rank):
                neighbor=['1']*rank
                neighbor[dim]='2'
                stride_code+=f'''    if (size(array)>0 .and. size(array,{dim+1})>1) then
      view%strides({dim+1})=int(transfer(c_loc(array({', '.join(neighbor)})),0_c_intptr_t) - &
                            transfer(data,0_c_intptr_t),c_int64_t)
    end if
'''
            template=template.replace('    options%step = 0_c_int64_t',stride_code+'    options%step = 0_c_int64_t')
            for operation,native in (('borrow','c_borrow'),('submit_borrow','c_submit_borrow')):
                borrowed=template.replace(f'submit_{suffix}_{rank}(',f'{operation}_{suffix}_{rank}(')
                borrowed=borrowed.replace('rc = c_submit(',f'rc = {native}(')
                parts.append('\n'+borrowed+'\n')
    return ''.join(parts)


if __name__ == '__main__':
    (Path(__file__).resolve().parents[1]/'src/cotocoa_arrays.inc').write_text(generate())
